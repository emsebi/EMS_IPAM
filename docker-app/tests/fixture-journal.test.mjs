import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { randomUUID } from 'node:crypto';
import { createFixtureJournal, openFixtureJournal } from './helpers/fixture-journal.mjs';

test('fixture journal preserves private evidence and refuses overwrite, truncation and unowned removal', t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'ems-journal-'));
  t.after(() => fs.rmSync(directory, { recursive:true, force:true }));
  const filename = path.join(directory, 'journal.jsonl');
  const runId = randomUUID();
  const name = 'EMS XLSX fixture ' + runId + ' North';
  const id = randomUUID();
  const writer = createFixtureJournal(filename, runId);
  writer.record({kind:'creating', name});
  writer.record({kind:'created', name, id});
  writer.close();
  const original = fs.readFileSync(filename);
  assert.equal(fs.statSync(filename).mode & 0o777, 0o600);
  assert.throws(() => createFixtureJournal(filename, randomUUID()), {code:'EEXIST'});
  assert.deepEqual(fs.readFileSync(filename), original);
  const journal = openFixtureJournal(filename);
  assert.deepEqual(journal.owned, [{id,name}]);
  journal.record({kind:'purging',id});
  journal.close();
  const pending = openFixtureJournal(filename);
  assert.deepEqual(pending.owned, [{id,name,purging:true}]);
  pending.record({kind:'removed',id});
  pending.close();
  const finished = openFixtureJournal(filename);
  assert.deepEqual(finished.owned, []);
  finished.close();
  fs.writeFileSync(filename, original.subarray(0, original.length - 1));
  assert.throws(() => openFixtureJournal(filename), /incomplete/);
  fs.writeFileSync(filename, original);
  fs.appendFileSync(filename, JSON.stringify({kind:'removed',id:randomUUID(),observedAt:new Date().toISOString()})+'\n');
  assert.throws(() => openFixtureJournal(filename));
  fs.writeFileSync(filename, original);
  fs.chmodSync(filename, 0o644);
  assert.throws(() => openFixtureJournal(filename), /private/);
});
